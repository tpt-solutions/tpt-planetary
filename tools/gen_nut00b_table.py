#!/usr/bin/env python3
"""Generate tpt-planetary-astro/src/nutation_b_data.rs from ERFA's nut00b.c.

Usage: python tools/gen_nut00b_table.py path/to/nut00b.c

The table is the 77-term luni-solar series of IAU 2000B (McCarthy & Luzum
2003), as coded in ERFA's `eraNut00b` (derived from SOFA). Each row is
`(nl, nlp, nf, nd, nom, ps, pst, pc, ec, ect, es)`: the multipliers of the
Delaunay arguments and the amplitudes in units of 0.1 microarcsecond.
"""

import re
import sys
from pathlib import Path

ROWS = 77
ROW = re.compile(
    r"\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,"
    r"\s*([-+0-9.]+)\s*,\s*([-+0-9.]+)\s*,\s*([-+0-9.]+)\s*,"
    r"\s*([-+0-9.]+)\s*,\s*([-+0-9.]+)\s*,\s*([-+0-9.]+)\s*\}"
)


def parse(source: str):
    start = source.index("static const struct {")
    body = source[start:source.index("};", start)]
    body = body[body.index("x[] = {") :]
    rows = [m.groups() for m in ROW.finditer(body)]
    if len(rows) != ROWS:
        raise SystemExit(f"expected {ROWS} rows, found {len(rows)}")
    return rows


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    rows = parse(Path(argv[1]).read_text(encoding="utf-8"))
    out = Path(__file__).resolve().parent.parent / "tpt-planetary-astro" / "src" / "nutation_b_data.rs"
    lines = [
        "//! IAU 2000B luni-solar nutation terms, generated by",
        "//! `tools/gen_nut00b_table.py` from ERFA's `nut00b.c` (derived from SOFA).",
        "//! Do not edit by hand.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::excessive_precision)]",
        "",
        "/// Terms `((nl, nlp, nf, nd, nom), (ps, pst, pc, ec, ect, es))`. The multipliers",
        "/// are of the Delaunay arguments (l, l', F, D, Omega); the amplitudes are in",
        "/// units of 0.1 microarcsecond, with `pst` and `ect` per Julian century.",
        f"pub(crate) static NUT00B_TERMS: [([i32; 5], [f64; 6]); {ROWS}] = [",
    ]
    for r in rows:
        mult = ", ".join(r[:5])
        amp = ", ".join(r[5:])
        lines.append(f"    ([{mult}], [{amp}]),")
    lines.append("];")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({ROWS} terms)")


if __name__ == "__main__":
    main(sys.argv)
