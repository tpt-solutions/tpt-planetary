#!/usr/bin/env python3
"""Generate tpt-planetary-astro/src/tdb_data.rs from ERFA's dtdb.c.

Usage: python tools/gen_tdb_table.py path/to/dtdb.c

The table is the Fairhead & Bretagnon (1990) series as coded in ERFA's
`eraDtdb` (derived from SOFA, BSD-style licence, see the ERFA source). Each
row is `{amplitude_s, frequency_rad_per_millennium, phase_rad}`. The rows are
grouped by the power of T they multiply, in the order used by `eraDtdb`:
T^0 (rows 0..474), T^1 (474..679), T^2 (679..764), T^3 (764..784) and T^4
(784..787). The generator checks the row count and the group boundaries.
"""

import re
import sys
from pathlib import Path

# Exclusive end index of each power group, from the loops in eraDtdb.
GROUP_ENDS = [474, 679, 764, 784, 787]
ROWS = 787

ROW = re.compile(r"\{\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)\s*\}")


def parse(source: str):
    start = source.index("static const double fairhd[787][3] = {")
    body = source[start:source.index("};", start)]
    rows = [tuple(m.groups()) for m in ROW.finditer(body)]
    if len(rows) != ROWS:
        raise SystemExit(f"expected {ROWS} rows, found {len(rows)}")
    return rows


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    rows = parse(Path(argv[1]).read_text(encoding="utf-8"))
    out = Path(__file__).resolve().parent.parent / "tpt-planetary-astro" / "src" / "tdb_data.rs"
    lines = [
        "//! Fairhead & Bretagnon (1990) TDB - TT series, generated by",
        "//! `tools/gen_tdb_table.py` from ERFA's `dtdb.c` (derived from SOFA).",
        "//! Do not edit by hand.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::excessive_precision)]",
        "",
        "/// Number of rows in each power-of-T group, in order T^0 to T^4.",
        f"pub(crate) const FAIRHEAD_GROUP_ENDS: [usize; {len(GROUP_ENDS)}] = {GROUP_ENDS!r};",
        "",
        "/// Terms `(amplitude_s, frequency_rad_per_millennium, phase_rad)`. A term",
        "/// in group `k` contributes `amplitude * sin(frequency * t + phase)` times",
        "/// `t^k`, where `t` is Julian millennia since J2000 TT.",
        f"pub(crate) static FAIRHEAD_TERMS: [(f64, f64, f64); {ROWS}] = [",
    ]
    for a, f, p in rows:
        lines.append(f"    ({a}, {f}, {p}),")
    lines.append("];")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({ROWS} terms)")


if __name__ == "__main__":
    main(sys.argv)
