//! Bitshuffle: a bit-level transposition of fixed-size elements, followed by
//! LZ4 block compression, in the framing of the bitshuffle library's
//! `compress_lz4` (Masui), as used by numcodecs' `bitshuffle` codec and Zarr.
//!
//! # Transform (definition)
//!
//! Take `n` elements of `e` bytes each, with `n` a multiple of 8. Number the
//! bits of an element `p = 0 .. 8e`, where bit `p` is bit `p % 8` (LSB first)
//! of byte `p / 8` of the element's memory image. The shuffled block has `8e`
//! bit-planes of `n / 8` bytes each. Byte `p * (n / 8) + j` of the output
//! holds, at bit `k`, bit `p` of element `8 j + k`. Elements that do not fill
//! a group of 8 (the last `n % 8` elements) are copied unchanged to the end.
//!
//! # Framing (numcodecs `bitshuffle`, bitshuffle library `compress_lz4`)
//!
//! There is no header. The stream is:
//!
//! - for each block of `block_bytes` shuffled bytes (the last block may be
//!   shorter): a 4-byte big-endian length `c`, then `c` bytes. If `c` equals
//!   the block length the block is stored raw; otherwise the `c` bytes are an
//!   LZ4 block that decompresses to the block length. LZ4 output may be longer
//!   than its input, so `c` may exceed the block length.
//! - the trailing `nbytes - 8e * floor(nbytes / 8e)` bytes, copied raw.
//!
//! The decoder needs `nbytes` (the uncompressed size), which the stream does
//! not carry. Zarr supplies it from the chunk shape and dtype, so the codec
//! must be given it with [`BitshuffleCodec::with_nbytes`] before decoding.
//!
//! The default block size is 8192 bytes rounded down to a whole number of
//! groups of 8 elements, as in the bitshuffle library.
//!
//! Byte-level agreement with the reference library is tested against fixtures
//! generated by the Python package `bitshuffle` 0.5.2 (see `testdata/`).

use alloc::boxed::Box;
use alloc::format;
use alloc::vec;
use alloc::vec::Vec;

use serde_json::Value;

use super::{Codec, config_i64};
use crate::dtype::DType;
use crate::error::{Error, Result};

/// Block size used when the configuration does not give one (bytes).
const DEFAULT_BLOCK_BYTES: usize = 8192;

/// Largest expansion LZ4 can produce, rounded up. Used to reject frames whose
/// header claims an implausible uncompressed size before allocating.
pub(crate) const MAX_EXPANSION: usize = 1032;

/// Bit-plane transform of the whole groups of 8 elements in `src`, writing
/// into `dst` (which must be the same length and zeroed by the caller).
fn planes(src: &[u8], dst: &mut [u8], elem: usize, forward: bool) {
    let n = src.len() / elem;
    let groups = n / 8;
    for p in 0..8 * elem {
        let byte_idx = p / 8;
        let bit = p % 8;
        for j in 0..groups {
            for k in 0..8 {
                let elem_pos = (8 * j + k) * elem + byte_idx;
                let plane_pos = p * groups + j;
                if forward {
                    dst[plane_pos] |= ((src[elem_pos] >> bit) & 1) << k;
                } else {
                    dst[elem_pos] |= ((src[plane_pos] >> k) & 1) << bit;
                }
            }
        }
    }
}

/// Applies the transform (or its inverse) to the whole groups of 8 elements
/// and copies the trailing bytes unchanged.
fn transform(src: &[u8], elem: usize, forward: bool) -> Vec<u8> {
    let whole = src.len() / (8 * elem) * (8 * elem);
    let mut out = vec![0u8; src.len()];
    planes(&src[..whole], &mut out[..whole], elem, forward);
    out[whole..].copy_from_slice(&src[whole..]);
    out
}

/// Bit-shuffles `src` (elements of `elem` bytes), without compression.
pub(crate) fn bit_shuffle(src: &[u8], elem: usize) -> Vec<u8> {
    transform(src, elem, true)
}

/// Inverts [`bit_shuffle`].
pub(crate) fn bit_unshuffle(src: &[u8], elem: usize) -> Vec<u8> {
    transform(src, elem, false)
}

/// Bitshuffle codec for elements of `elementsize` bytes.
///
/// Encoding needs no extra information. Decoding needs the uncompressed size,
/// set with [`BitshuffleCodec::with_nbytes`].
#[derive(Debug, Clone, Copy)]
pub struct BitshuffleCodec {
    elementsize: usize,
    block_bytes: usize,
    nbytes: Option<usize>,
}

impl BitshuffleCodec {
    /// Creates a bitshuffle codec for elements of `elementsize` bytes.
    pub fn new(elementsize: usize) -> Result<Self> {
        if elementsize == 0 {
            return Err(Error::InvalidMetadata(
                "bitshuffle elementsize must be positive".into(),
            ));
        }
        Ok(Self {
            elementsize,
            block_bytes: default_block_bytes(elementsize),
            nbytes: None,
        })
    }

    /// Sets the block size in bytes. It must be a positive multiple of
    /// `8 * elementsize`, and at most `u32::MAX`.
    pub fn with_block_bytes(mut self, bytes: usize) -> Result<Self> {
        let unit = 8 * self.elementsize;
        if bytes == 0 || !bytes.is_multiple_of(unit) || bytes > u32::MAX as usize {
            return Err(Error::InvalidMetadata(format!(
                "bitshuffle block size {bytes} must be a positive multiple of {unit}"
            )));
        }
        self.block_bytes = bytes;
        Ok(self)
    }

    /// Sets the uncompressed size in bytes, needed to decode. For a Zarr chunk
    /// this is the product of the chunk shape times the item size.
    #[must_use]
    pub fn with_nbytes(mut self, nbytes: usize) -> Self {
        self.nbytes = Some(nbytes);
        self
    }

    /// Element size in bytes.
    pub fn elementsize(&self) -> usize {
        self.elementsize
    }

    /// Block size in bytes.
    pub fn block_bytes(&self) -> usize {
        self.block_bytes
    }

    /// The uncompressed size, if set.
    pub fn nbytes(&self) -> Option<usize> {
        self.nbytes
    }
}

fn default_block_bytes(elementsize: usize) -> usize {
    let groups = (DEFAULT_BLOCK_BYTES / elementsize / 8).max(1);
    groups * 8 * elementsize
}

/// Reads `n` bytes at `*pos` and advances the cursor.
fn take<'a>(input: &'a [u8], pos: &mut usize, n: usize) -> Result<&'a [u8]> {
    let end = pos
        .checked_add(n)
        .filter(|&e| e <= input.len())
        .ok_or_else(|| Error::Codec("bitshuffle: truncated stream".into()))?;
    let s = &input[*pos..end];
    *pos = end;
    Ok(s)
}

fn be_u32(bytes: &[u8]) -> u32 {
    u32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]])
}

impl Codec for BitshuffleCodec {
    fn name(&self) -> &str {
        "bitshuffle"
    }

    fn encode(&self, input: &[u8]) -> Result<Vec<u8>> {
        let e = self.elementsize;
        let block = self.block_bytes;
        let whole = input.len() / (8 * e) * (8 * e);
        let mut out = Vec::with_capacity(input.len() + 4);
        let mut off = 0;
        while off < whole {
            let bs = block.min(whole - off);
            let shuffled = bit_shuffle(&input[off..off + bs], e);
            let compressed = lz4_flex::block::compress(&shuffled);
            if compressed.len() < bs {
                let c = u32::try_from(compressed.len())
                    .map_err(|_| Error::Codec("bitshuffle: block exceeds u32".into()))?;
                out.extend_from_slice(&c.to_be_bytes());
                out.extend_from_slice(&compressed);
            } else {
                let c = u32::try_from(bs)
                    .map_err(|_| Error::Codec("bitshuffle: block exceeds u32".into()))?;
                out.extend_from_slice(&c.to_be_bytes());
                out.extend_from_slice(&shuffled);
            }
            off += bs;
        }
        out.extend_from_slice(&input[whole..]);
        Ok(out)
    }

    fn decode(&self, input: &[u8]) -> Result<Vec<u8>> {
        let e = self.elementsize;
        let block = self.block_bytes;
        let nbytes = self.nbytes.ok_or_else(|| {
            Error::Codec("bitshuffle: decoding needs the uncompressed size (with_nbytes)".into())
        })?;
        let whole = nbytes / (8 * e) * (8 * e);
        let mut out = vec![0u8; nbytes];
        let mut pos = 0usize;
        let mut off = 0;
        while off < whole {
            let bs = block.min(whole - off);
            let c = be_u32(take(input, &mut pos, 4)?) as usize;
            let shuffled = if c == bs {
                take(input, &mut pos, bs)?.to_vec()
            } else {
                let comp = take(input, &mut pos, c)?;
                let mut buf = vec![0u8; bs];
                let got = lz4_flex::block::decompress_into(comp, &mut buf)
                    .map_err(|err| Error::Codec(format!("bitshuffle: lz4: {err}")))?;
                if got != bs {
                    return Err(Error::Codec(format!(
                        "bitshuffle: lz4 block produced {got} bytes, expected {bs}"
                    )));
                }
                buf
            };
            out[off..off + bs].copy_from_slice(&bit_unshuffle(&shuffled, e));
            off += bs;
        }

        let tail = nbytes - whole;
        if input.len() - pos != tail {
            return Err(Error::Codec(
                "bitshuffle: stream length does not match the uncompressed size".into(),
            ));
        }
        out[whole..].copy_from_slice(&input[pos..]);
        Ok(out)
    }
}

pub(crate) fn bitshuffle_factory(config: &Value, dtype: &DType) -> Result<Box<dyn Codec>> {
    Ok(Box::new(bitshuffle_for_size(config, dtype, None)?))
}

/// Builds the bitshuffle codec from its configuration, with the uncompressed
/// size when it is known (Zarr supplies it from the chunk shape).
pub(crate) fn bitshuffle_for_size(
    config: &Value,
    dtype: &DType,
    nbytes: Option<usize>,
) -> Result<BitshuffleCodec> {
    let es = match config_i64(config, "elementsize")? {
        None | Some(0) => dtype.item_size(),
        Some(v) if v > 0 => v as usize,
        Some(v) => {
            return Err(Error::InvalidMetadata(format!(
                "bitshuffle elementsize {v} must be non-negative"
            )));
        }
    };
    let codec = BitshuffleCodec::new(es)?;
    Ok(match nbytes {
        Some(n) => codec.with_nbytes(n),
        None => codec,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hand_computed_eight_one_byte_elements() {
        // Elements 0..=7 (1 byte each). Plane p collects bit p of each
        // element: plane 0 has bits k with k odd (1,3,5,7) -> 0b1010_1010 =
        // 0xAA; plane 1 has k in {2,3,6,7} -> 0xCC; plane 2 has k in
        // {4,5,6,7} -> 0xF0; planes 3..=7 are zero.
        let input = [0u8, 1, 2, 3, 4, 5, 6, 7];
        assert_eq!(
            bit_shuffle(&input, 1),
            vec![0xAA, 0xCC, 0xF0, 0, 0, 0, 0, 0]
        );
        assert_eq!(bit_unshuffle(&[0xAA, 0xCC, 0xF0, 0, 0, 0, 0, 0], 1), input);
    }

    #[test]
    fn four_elements_are_a_remainder_and_unchanged() {
        // Fewer than 8 elements: nothing is transposed.
        let input = [1u8, 2, 3, 4];
        assert_eq!(bit_shuffle(&input, 1), input.to_vec());
    }

    #[test]
    fn round_trip_typesizes_and_lengths() {
        for e in [1usize, 2, 4, 8] {
            for n_elems in [0usize, 1, 5, 8, 13, 64, 100, 1000] {
                let data: Vec<u8> = (0..n_elems * e + (e - 1).min(1))
                    .map(|i| (i * 37 % 251) as u8)
                    .collect();
                let codec = BitshuffleCodec::new(e).unwrap().with_nbytes(data.len());
                let enc = codec.encode(&data).unwrap();
                assert_eq!(codec.decode(&enc).unwrap(), data, "e={e} n={n_elems}");
                // Small blocks force several blocks and a short last block.
                let small = codec
                    .with_block_bytes(8 * e * 2)
                    .unwrap()
                    .with_nbytes(data.len());
                let enc = small.encode(&data).unwrap();
                assert_eq!(small.decode(&enc).unwrap(), data, "small e={e} n={n_elems}");
            }
        }
    }

    #[test]
    fn default_block_size_matches_library_rule() {
        assert_eq!(BitshuffleCodec::new(1).unwrap().block_bytes(), 8192);
        assert_eq!(BitshuffleCodec::new(4).unwrap().block_bytes(), 8192);
        // 8192 / 3 = 2730 elements, rounded down to a multiple of 8: 2728 * 3.
        assert_eq!(BitshuffleCodec::new(3).unwrap().block_bytes(), 8184);
    }

    #[test]
    fn rejects_bad_block_truncation_and_missing_size() {
        let codec = BitshuffleCodec::new(4).unwrap();
        assert!(codec.with_block_bytes(20).is_err());
        assert!(codec.with_block_bytes(0).is_err());
        let data: Vec<u8> = (0..200u8).collect();
        let sized = codec.with_nbytes(data.len());
        let enc = sized.encode(&data).unwrap();
        assert!(sized.decode(&enc[..enc.len() - 1]).is_err());
        assert!(sized.decode(&enc[..3]).is_err());
        // Without the size the codec cannot decode.
        assert!(codec.decode(&enc).is_err());
    }

    #[test]
    fn factory_uses_dtype_when_elementsize_absent() {
        let r = super::super::Registry::builtin();
        let c = r
            .build(
                "bitshuffle",
                &serde_json::json!({"elementsize": 0}),
                &DType::FLOAT64,
            )
            .unwrap();
        assert_eq!(c.name(), "bitshuffle");
        // The registry codec has no size, so it encodes but does not decode.
        let data: Vec<u8> = (0..80u8).collect();
        assert!(c.encode(&data).is_ok());
    }
}

#[cfg(test)]
mod reference_tests {
    //! Byte-level checks against the reference `bitshuffle` library (Python
    //! package `bitshuffle` 0.5.2, generated fixtures in `testdata/`).
    use super::*;

    #[test]
    fn bit_shuffle_matches_reference_library() {
        let raw = include_bytes!("testdata/bs_u8_1000.raw");
        let shuffled = include_bytes!("testdata/bs_u8_1000.shuffled");
        assert_eq!(bit_shuffle(raw, 1).as_slice(), &shuffled[..]);
    }

    #[test]
    fn decodes_reference_stream_u8() {
        let raw = include_bytes!("testdata/bs_u8_1000.raw");
        let framed = include_bytes!("testdata/bs_u8_1000.lz4framed");
        let c = BitshuffleCodec::new(1).unwrap().with_nbytes(raw.len());
        assert_eq!(c.decode(framed).unwrap().as_slice(), &raw[..]);
    }

    #[test]
    fn decodes_reference_stream_i32_with_remainder() {
        let raw = include_bytes!("testdata/bs_i32_333.raw");
        let framed = include_bytes!("testdata/bs_i32_333.lz4framed");
        let c = BitshuffleCodec::new(4).unwrap().with_nbytes(raw.len());
        assert_eq!(c.decode(framed).unwrap().as_slice(), &raw[..]);
    }

    #[test]
    fn decodes_reference_stream_with_several_blocks() {
        // 20000 bytes at the default 8192-byte block: three blocks.
        let raw = include_bytes!("testdata/bs_u8_20000.raw");
        let framed = include_bytes!("testdata/bs_u8_20000.lz4framed");
        let c = BitshuffleCodec::new(1).unwrap().with_nbytes(raw.len());
        assert_eq!(c.decode(framed).unwrap().as_slice(), &raw[..]);
    }

    #[test]
    fn decodes_incompressible_block_whose_lz4_output_is_longer() {
        // A block whose LZ4 output (8226 bytes) exceeds its 8192-byte input.
        let raw = include_bytes!("testdata/bs_u8_random9000.raw");
        let framed = include_bytes!("testdata/bs_u8_random9000.lz4framed");
        let c = BitshuffleCodec::new(1).unwrap().with_nbytes(raw.len());
        assert_eq!(c.decode(framed).unwrap().as_slice(), &raw[..]);
    }

    #[test]
    fn our_encoding_round_trips_through_the_reference_sizes() {
        for (raw, e) in [
            (&include_bytes!("testdata/bs_u8_20000.raw")[..], 1usize),
            (&include_bytes!("testdata/bs_u8_random9000.raw")[..], 1),
            (&include_bytes!("testdata/bs_i32_333.raw")[..], 4),
        ] {
            let c = BitshuffleCodec::new(e).unwrap().with_nbytes(raw.len());
            assert_eq!(c.decode(&c.encode(raw).unwrap()).unwrap(), raw);
        }
    }
}
